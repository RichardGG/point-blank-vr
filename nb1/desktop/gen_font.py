#!/usr/bin/env python3
"""Generate desktop/font7x13.h (ASCII 32..126, 7x13 cells, 1 bit per pixel) from DejaVu Sans Mono.
DejaVu fonts: Bitstream Vera / public-domain licence terms, see https://dejavu-fonts.github.io/License.html"""
import sys
from PIL import Image, ImageDraw, ImageFont
font = ImageFont.truetype(sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf', 12)
rows = []
for c in range(32, 127):
    im = Image.new('L', (7, 13), 0); ImageDraw.Draw(im).text((0, -1), chr(c), fill=255, font=font)
    px = im.load(); rows.append([sum((1 << (6 - x)) for x in range(7) if px[x, y] >= 110) for y in range(13)])
with open('font7x13.h', 'w') as f:
    f.write('/* generated by gen_font.py from DejaVu Sans Mono: ASCII 32..126, 13 rows per glyph, bit 6 = leftmost pixel */\n')
    f.write('static const unsigned char FONT7X13[95][13] = {\n')
    for r in rows: f.write('  {' + ','.join('0x%02x' % v for v in r) + '},\n')
    f.write('};\n')
print('ok')
